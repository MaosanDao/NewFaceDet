    public static FaceDetectSDK with() {
        if (faceSDK == null) {
            synchronized (FaceDetectSDK.class) {
                if (faceSDK == null) {
                    faceSDK = new FaceDetectSDK();
                }
            }
        }
        return faceSDK;
    }

