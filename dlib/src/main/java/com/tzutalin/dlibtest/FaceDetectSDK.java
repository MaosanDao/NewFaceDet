    /**
     * 重置数据
     */
    private void resetMotionsList() {
        mMotions.clear();
        mMotions.add(Constants.MOTION_MOUTH);
        mMotions.add(Constants.MOTION_EYE);
        mMotions.add(Constants.MOTION_HEAD);
    }

    /**
     * 初始化
     *
     * @param context Context
     */
    public FaceDetectSDK init(Activity context
            , AutoFitTextureView textTrueView) {

        if (textTrueView.isAvailable()) {
            FaceDetectSDK.with().openCamera(textTrueView, context, textTrueView.getWidth(), textTrueView.getHeight());
        } else {
            textTrueView.setSurfaceTextureListener(surfaceTextureListener);
        }

        this.mContext = context;
        this.mTextTrueView = textTrueView;

        //重置数据
        resetMotionsList();
        if (!isSetMotions) {
            //先随机看几种验证方式
            mMotionSum = Constants.MOTIONS_NUM;
            //随机的最后校验顺序
            mLastMotions = getRandomTypeFromMotionsList(mMotionSum);
        }

        //重置数据
        resetMotionsList();

        return this;
    }


    /**
     * Starts a background thread and its {@link Handler}.
     */
    @DebugLog
    private void startBackgroundThread() {
        backgroundThread = new HandlerThread("ImageListener");
        backgroundThread.start();
        backgroundHandler = new Handler(backgroundThread.getLooper());

        inferenceThread = new HandlerThread("InferenceThread");
        inferenceThread.start();
        inferenceHandler = new Handler(inferenceThread.getLooper());
    }

    /**
     * Stops the background thread and its {@link Handler}.
     */
    @SuppressLint("LongLogTag")
    @DebugLog
    private void stopBackgroundThread() {
        backgroundThread.quitSafely();
        inferenceThread.quitSafely();
        try {
            backgroundThread.join();
            backgroundThread = null;
            backgroundHandler = null;

            inferenceThread.join();
            inferenceThread = null;
            inferenceHandler = null;
        } catch (final InterruptedException e) {
            e.printStackTrace();
        }
    }

